import asyncio, re
from playwright.async_api import async_playwright
from common import *
L=Log(); errs=[]
APP="http://localhost:8081/app"
CLIENT=open("tests/.local/client_email").read().strip()
async def login(pg, email, pw):
    await pg.goto(APP); await pg.wait_for_url("**/connexion", timeout=20000)
    ins=pg.locator("input")
    await ins.nth(0).fill(email); await ins.nth(1).fill(pw)
    await pg.get_by_role("button", name="Se connecter").last.click()
    await pg.wait_for_timeout(2500)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(channel="chrome", args=["--no-sandbox"])
        ctx=await b.new_context(viewport={"width":390,"height":844}, locale="fr-FR")
        pg=await new_page(ctx, errs)
        print("== App : client")
        await login(pg, CLIENT, "NouveauMdp-2026")
        txt=await pg.inner_text("body")
        L.check("bonjour" in txt.lower(), "app client : accueil « Bonjour … »")
        L.check("ouvrira" in txt.lower() or "très vite" in txt.lower(), "app client : bandeau commande fermée")
        await pg.screenshot(path="tests/.local/shots/app1_accueil_client.png", full_page=True)
        for tab in ["Commandes","Fidélité","Compte"]:
            await pg.get_by_role("tab", name=re.compile(tab)).first.click() if await pg.get_by_role("tab", name=re.compile(tab)).count() else await pg.get_by_text(tab, exact=True).last.click()
            await pg.wait_for_timeout(1500); await pg.screenshot(path=f"tests/.local/shots/app_{tab}.png", full_page=True)
            L.ok(f"app client : onglet {tab}")
        txt=await pg.inner_text("body"); L.check("@" in txt, "compte : e-mail affiché")
        await pg.get_by_role("button", name="Se déconnecter").click(); await pg.wait_for_timeout(2000)
        L.check("/connexion" in pg.url, f"déconnexion → {pg.url.replace(APP,'')}")
        print("== App : équipe")
        await login(pg, "admin@test.local", ADMIN_PW)
        txt=await pg.inner_text("body"); L.check("Aperçu équipe" in txt, "app équipe : bandeau aperçu")
        await pg.get_by_role("button", name=re.compile("Commander À emporter")).click(); await pg.wait_for_timeout(2500)
        await pg.locator("input").first.fill("12:45")
        adds=pg.get_by_role("button", name="Ajouter", exact=True)
        L.check(await adds.count()>5, f"app : carte affichée ({await adds.count()} articles)")
        await adds.nth(0).click(); await pg.wait_for_timeout(300); await pg.get_by_role("button", name=re.compile("^Ajouter un ")).first.click()
        await pg.get_by_role("button", name=re.compile("Voir le panier")).click(); await pg.wait_for_timeout(1500)
        await pg.screenshot(path="tests/.local/shots/app2_panier.png", full_page=True)
        await pg.get_by_role("button", name=re.compile("Payer ma commande|Valider")).click()
        await pg.wait_for_url("**/payer/**", timeout=20000); L.ok("app : redirigé vers la page de paiement")
        await pg.get_by_role("button", name=re.compile("Simuler le paiement")).click()
        await pg.wait_for_url("**/merci", timeout=20000); L.ok("app : paiement simulé → « Paiement reçu »")
        await pg.goto(APP); await pg.wait_for_timeout(2500)
        txt=await pg.inner_text("body"); L.check("Suivre ma commande" in txt, "app : commande en cours affichée à l'accueil")
        await pg.get_by_text("Suivre ma commande").click(); await pg.wait_for_timeout(2000)
        await pg.screenshot(path="tests/.local/shots/app3_suivi.png", full_page=True)
        L.check("C'est parti" in await pg.inner_text("body") or "Reçue" in await pg.inner_text("body"), "app : écran de suivi")
        print("== App : onglet Équipe")
        await pg.goto(APP); await pg.wait_for_timeout(2500); await pg.get_by_text("Équipe", exact=True).last.click(); await pg.wait_for_timeout(3000)
        txt=await pg.inner_text("body"); L.check("nouvelles" in txt.lower() or "prêtes" in txt.lower(), "app équipe : commandes en cours")
        await pg.screenshot(path="tests/.local/shots/app4_equipe.png", full_page=True)
        await pg.get_by_role("button", name=re.compile("Nouvelle commande")).click(); await pg.wait_for_timeout(2500)
        await pg.locator("input").first.fill("7")
        adds=pg.get_by_role("button", name="Ajouter", exact=True); await adds.nth(2).click(); await adds.nth(5).click()
        await pg.get_by_role("radio", name=re.compile("Plus tard")).click()
        await pg.screenshot(path="tests/.local/shots/app5_nouvelle.png", full_page=True)
        await pg.get_by_role("button", name="Envoyer en cuisine").click(); await pg.wait_for_timeout(2500)
        txt=await pg.inner_text("body"); L.check("envoyée" in txt.lower(), "app équipe : commande à table envoyée")
        ok=pg.get_by_role("button", name="OK")
        if await ok.count(): await ok.click()
        await pg.wait_for_timeout(2000)
        txt=await pg.inner_text("body"); L.check("À encaisser" in txt, "app équipe : badge « À encaisser »")
        await pg.get_by_role("button", name="Encaisser").first.click(); await pg.wait_for_timeout(800)
        await pg.get_by_role("button", name="Terminal SumUp").click(); await pg.wait_for_timeout(2500)
        L.check("Encaissée au terminal" in await pg.inner_text("body"), "app équipe : encaissement au terminal")
        if await pg.get_by_role("button", name="OK").count(): await pg.get_by_role("button", name="OK").click()
        await pg.get_by_role("button", name="Préparer").first.click(); await pg.wait_for_timeout(2000)
        await pg.get_by_role("button", name="Prête").first.click(); await pg.wait_for_timeout(2000)
        pc=pg.get_by_role("button", name=re.compile("Prévenir le client"))
        if await pc.count():
            await pc.first.click(); await pg.wait_for_timeout(2500); t=await pg.inner_text("body")
            L.check("prévenu" in t or "Ni application" in t, "app équipe : prévenir le client → réponse affichée")
        await pg.screenshot(path="tests/.local/shots/app6_equipe_apres.png", full_page=True)
        await b.close()
asyncio.run(main())
print("\nERREURS CONSOLE:", [e for e in errs if "WebSocket" not in e][:8])
print("RESUME:", [m for s,m in L.items if s=="BUG"])
