import asyncio, re
from playwright.async_api import async_playwright
from common import *
L=Log(); errs=[]
CLIENT=open("tests/.local/client_email").read().strip()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(channel="chrome", args=["--no-sandbox"])
        a=await new_page(await b.new_context(viewport={"width":1280,"height":900}), errs)
        await a.goto(BASE+"/admin/connexion"); await a.fill("#a-mail","admin@test.local"); await a.fill("#a-mdp",ADMIN_PW); await a.get_by_role("button", name="Se connecter").click(); await a.wait_for_url(BASE+"/admin")
        print("== Fidélité : objectif 2 tampons")
        await a.goto(BASE+"/admin/reglages"); await a.fill("#loyalty_goal","2"); await a.fill("#loyalty_reward","5,00")
        await a.check('input[name="ordering_open"]'); await a.get_by_role("button", name="Enregistrer").click(); await asyncio.sleep(1.5)
        await a.goto(BASE+"/commander/emporter"); await a.wait_for_load_state("networkidle")
        rw=a.get_by_text("Utiliser ma récompense fidélité")
        L.check(await rw.count()>0, "récompense fidélité proposée au panier")
        adds=a.get_by_role("button", name=re.compile("^Ajouter ")); await adds.nth(0).click()
        await a.fill("#lieu","13:00")
        before=await a.locator("aside").inner_text()
        await rw.click(); after=await a.locator("aside").inner_text()
        L.check("19,00" in after, f"total remisé de 5 € (24,00 → 19,00) : {'19,00' in after}")
        await a.get_by_role("button", name="Payer ma commande").click(); await a.wait_for_url("**/paiement/**")
        L.check("19,00" in await a.inner_text("body"), "montant à payer = 19,00 €")
        await a.get_by_role("button", name=re.compile("Simuler")).click(); await a.wait_for_url("**/commande/**")
        L.check("Fidélité" in await a.inner_text("body"), "ligne « Fidélité » sur la commande")
        await a.goto(BASE+"/compte"); txt=await a.inner_text("body")
        L.check("carte de fidélité" in txt.lower(), "espace client : carte de fidélité")
        print("== Commande ouverte au public, SumUp non branché")
        c=await new_page(await b.new_context(viewport={"width":390,"height":844}), errs)
        await c.goto(BASE+"/connexion?suite=/commander/emporter"); await c.fill("#mail",CLIENT); await c.fill("#mdp","NouveauMdp-2026"); await c.get_by_role("button", name="Se connecter", exact=True).click()
        await c.wait_for_url("**/commander/emporter", timeout=15000); await c.wait_for_load_state("networkidle")
        L.check("paiement en ligne est en cours d'installation" in (await c.inner_text("body")), "client : message clair « paiement en cours d'installation », pas de panier inutile")
        await c.screenshot(path="tests/.local/shots/x_client_open_nosumup.png", full_page=True)
        print("== Mobile : barre panier + suivi")
        m=await new_page(await b.new_context(viewport={"width":390,"height":844}, storage_state=await a.context.storage_state()), errs)
        await m.goto(BASE+"/commander/table?t=7"); await m.wait_for_load_state("networkidle")
        L.check(await m.input_value("#lieu")=="7", "n° de table pré-rempli depuis le lien (?t=7)")
        await m.get_by_role("button", name=re.compile("^Ajouter ")).nth(2).click()
        bar=m.locator(".cartbar"); L.check(await bar.is_visible(), "barre panier visible en bas sur mobile")
        await m.screenshot(path="tests/.local/shots/x_cartbar.png")
        await bar.click(); await asyncio.sleep(0.8)
        L.check(await m.locator("#panier").is_visible(), "la barre amène au panier")
        await a.goto(BASE+"/admin/reglages"); await a.uncheck('input[name="ordering_open"]'); await a.fill("#loyalty_goal","10"); await a.get_by_role("button", name="Enregistrer").click(); await asyncio.sleep(1.5)
        print("== Pages publiques mobiles")
        p2=await new_page(await b.new_context(viewport={"width":390,"height":844}), errs)
        for path in ["/","/carte","/commander","/connexion","/nexiste-pas"]:
            await p2.goto(BASE+path); await p2.wait_for_load_state("networkidle")
            over=await p2.evaluate("document.documentElement.scrollWidth > window.innerWidth+1")
            L.check(not over, f"mobile {path} sans débordement")
            await p2.screenshot(path=f"tests/.local/shots/y_{path.strip('/').replace('/','_') or 'home'}.png")
        await b.close()
asyncio.run(main())
print("ERREURS:", [e for e in errs if "WebSocket" not in e][:6])
print("RESUME:", [m for s,m in L.items if s=="BUG"])
