import asyncio, sys, time
from playwright.async_api import async_playwright, expect
from common import *
L=Log(); errs=[]
EMAIL=f"client{int(time.time())}@test.local"; PW="ClientTest-2026"
async def main():
    clear_mails()
    async with async_playwright() as p:
        b=await p.chromium.launch(channel="chrome", args=["--no-sandbox"])
        ctx=await b.new_context(viewport={"width":390,"height":844}, locale="fr-FR")
        pg=await new_page(ctx, errs)
        print("== Inscription")
        await pg.goto(BASE+"/commander"); await pg.get_by_role("link", name="À emporter au comptoir").click()
        await pg.wait_for_url("**/connexion**")
        L.check(await pg.get_by_role("tab", name="Se connecter").get_attribute("aria-selected")=="true", "onglet « Se connecter » actif par défaut")
        await pg.get_by_role("tab", name="Créer un compte").click()
        await pg.fill("#nom","Martin"); await pg.fill("#prenom","Camille"); await pg.fill("#tel","06 12 34 56 78"); await pg.fill("#cp","44000")
        await pg.fill("#mh","42"); await pg.fill("#mail",EMAIL); await pg.fill("#mdp",PW)
        await pg.get_by_role("button", name="Afficher le mot de passe").click()
        L.check(await pg.get_attribute("#mdp","type")=="text", "bouton œil affiche le mot de passe")
        await pg.get_by_role("button", name="Créer mon compte").click()
        await pg.get_by_role("status").wait_for(timeout=15000)
        L.check("Compte créé" in await pg.get_by_role("status").inner_text(), "inscription : message de succès")
        await pg.screenshot(path="tests/.local/shots/c1_inscription.png", full_page=True)
        await asyncio.sleep(1)
        m=last_mail(EMAIL)
        L.check(m is not None, f"e-mail de confirmation reçu ({m and m['subject']})")
        link=link_in(m,"/auth/confirm") if m else None
        L.check(bool(link), "lien de confirmation présent dans l'e-mail")
        print("== Connexion avant confirmation")
        pg2=await new_page(await b.new_context(viewport={"width":390,"height":844}), errs)
        await pg2.goto(BASE+"/connexion"); await pg2.fill("#mail",EMAIL); await pg2.fill("#mdp",PW); await pg2.get_by_role("button", name="Se connecter", exact=True).click()
        await pg2.locator("p.err").wait_for(); msg=await pg2.locator("p.err").inner_text()
        L.check("confirm" in msg.lower(), f"connexion avant confirmation : message clair ? « {msg} »")
        print("== Confirmation")
        await pg.goto(link); await pg.wait_for_load_state("networkidle")
        L.check("/commander/emporter" in pg.url or "/compte" in pg.url, f"après confirmation → {pg.url.replace(BASE,'')}")
        await asyncio.sleep(1)
        L.check(last_mail(EMAIL,"bienvenue") is not None, "e-mail de bienvenue envoyé après confirmation")
        await pg.screenshot(path="tests/.local/shots/c2_apres_confirmation.png", full_page=True)
        print("== Espace client")
        await pg.goto(BASE+"/compte"); await pg.wait_for_load_state("networkidle")
        L.check(await pg.get_by_text("Bonjour Camille").count()>0, "espace client : « Bonjour Camille »")
        L.check(await pg.get_by_text("Carte de fidélité").count()>0, "espace client : carte de fidélité affichée")
        await pg.screenshot(path="tests/.local/shots/c3_compte.png", full_page=True)
        await pg.locator('a[href="/commander#table"]').click(); await pg.wait_for_url("**/commander**"); await pg.wait_for_load_state("networkidle")
        L.check("/commander" in pg.url, f"raccourci À table → {pg.url.replace(BASE,'')}")
        print("== Commande fermée au public")
        await pg.goto(BASE+"/commander/emporter"); await pg.wait_for_load_state("networkidle")
        L.check(await pg.get_by_text("ouvrira avec le restaurant").count()>0, "client : commande fermée → message d'attente")
        print("== Profil")
        await pg.goto(BASE+"/compte")
        ph=pg.locator("#p-tel")
        if await ph.count():
            await ph.fill("07 00 00 00 01"); await pg.get_by_role("button", name="Enregistrer").click(); await asyncio.sleep(1.5)
            await pg.reload(); L.check(await pg.input_value("#p-tel")=="07 00 00 00 01", "profil : téléphone enregistré")
        print("== Mot de passe oublié")
        clear_mails()
        pg3=await new_page(await b.new_context(viewport={"width":390,"height":844}), errs)
        await pg3.goto(BASE+"/connexion"); await pg3.fill("#mail",EMAIL); await pg3.get_by_role("button", name="Mot de passe oublié ?").click()
        await pg3.get_by_role("status").wait_for(); await asyncio.sleep(1)
        rm=last_mail(EMAIL); L.check(rm is not None, f"e-mail mot de passe oublié reçu ({rm and rm['subject']})")
        rl=link_in(rm,"/auth/confirm") if rm else None
        if rl:
            await pg3.goto(rl); await pg3.wait_for_load_state("networkidle")
            L.check("/mot-de-passe" in pg3.url, f"lien de réinitialisation → {pg3.url.replace(BASE,'')}")
            await pg3.fill("#pw","NouveauMdp-2026"); await pg3.fill("#pw2","NouveauMdp-2026")
            await pg3.get_by_role("button", name="Enregistrer et entrer").click(); await pg3.wait_for_load_state("networkidle"); await asyncio.sleep(1.5)
            L.check("/compte" in pg3.url, f"nouveau mot de passe → {pg3.url.replace(BASE,'')}")
            await pg3.goto(rl); await pg3.wait_for_load_state("networkidle")
            L.check("expire" in pg3.url or await pg3.get_by_text("expiré").count()>0, f"lien déjà utilisé → message « expiré » ({pg3.url.replace(BASE,'')})")
        print("== Déconnexion / header")
        hdr=await pg.locator("header").inner_text()
        L.check("Mon compte" in hdr, "en-tête : « Mon compte » quand connecté")
        L.check(await pg.get_by_role("button", name="Se déconnecter").count()+await pg.get_by_role("link", name="Se déconnecter").count()>0, "un bouton « Se déconnecter » existe sur le site")
        await b.close()
    open("tests/.local/client_email","w").write(EMAIL)
asyncio.run(main())
print("\nERREURS CONSOLE:", errs[:10])
print("RESUME:", [m for s,m in L.items if s=="BUG"])
