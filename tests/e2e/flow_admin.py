        await pg.select_option("#m-cat", index=1)
        await pg.get_by_role("button", name="Ajouter à la carte").click(); t=await toast(pg); L.check("ajouté" in t.lower(), f"ajout produit carte : « {t} »")
        await pg.reload(); L.check(await pg.get_by_text("Test croque-monsieur").count()>0, "produit visible après rechargement")
        row=pg.locator("tr").filter(has_text="Test croque-monsieur").first
        await row.get_by_role("button").first.click(); await pg.fill("#m-price","9,00"); await pg.get_by_role("button", name="Enregistrer").click()
        t=await toast(pg); L.check("modifié" in t.lower(), f"modification produit : « {t} »")
        await pg.get_by_role("button", name=re.compile("Catégorie")).click(); await pg.fill("#c-name","Desserts test"); await pg.get_by_role("button", name="Enregistrer").click()
