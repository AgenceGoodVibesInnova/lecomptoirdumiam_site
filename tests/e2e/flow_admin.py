        mv=pg.get_by_role("button", name=re.compile("Mouvement")).first
        L.check(await mv.count()>0, "bouton « ± Mouvement » présent")
        print("== Clients")
        await pg.goto(BASE+"/admin/clients"); await pg.wait_for_load_state("networkidle")
