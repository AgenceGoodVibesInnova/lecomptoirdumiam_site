        print("== Équipe")
        await pg.goto(BASE+"/admin/equipe"); await pg.wait_for_load_state("networkidle")
        await pg.get_by_role("button", name=re.compile("Inviter une personne")).click()
        await pg.fill("#inv-mail","serveur@test.local"); await pg.select_option("#inv-role","editeur")
        await pg.get_by_role("button", name="Envoyer l'invitation").click(); t=await toast(pg); L.check("invitation envoy" in t.lower(), f"invitation : « {t} »")
