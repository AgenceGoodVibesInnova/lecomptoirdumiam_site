import asyncio, time
from playwright.async_api import async_playwright
from common import *
L=Log(); errs=[]
CLIENT=open("tests/.local/client_email").read().strip()
async def toast(pg):
    await asyncio.sleep(0.9)
    t=pg.locator(".a-toast, .a-flash.ok, .a-flash.err")
    return " | ".join([x.strip() for x in await t.all_inner_texts() if x.strip()])[:160]
async def main():
    clear_mails()
    async with async_playwright() as p:
        b=await p.chromium.launch(channel="chrome", args=["--no-sandbox"])
        ctx=await b.new_context(viewport={"width":1366,"height":900}, locale="fr-FR")
        pg=await new_page(ctx, errs)
        print("== Connexion admin")
        await pg.goto(BASE+"/admin"); await pg.wait_for_url("**/admin/connexion**")
        await pg.fill("#a-mail","admin@test.local"); await pg.fill("#a-mdp",ADMIN_PW)
        await pg.get_by_role("button", name="Se connecter").click(); await pg.wait_for_url(BASE+"/admin", timeout=15000)
        L.ok("connexion admin → tableau de bord")
        await pg.screenshot(path="tests/.local/shots/a1_dashboard.png", full_page=True)
        for path in ["/admin/cuisine","/admin/commandes","/admin/carte","/admin/stocks","/admin/clients","/admin/equipe","/admin/reglages"]:
            r=await pg.goto(BASE+path); await pg.wait_for_load_state("networkidle")
            L.check(r.status==200, f"page {path} ({r.status})")
            await pg.screenshot(path=f"tests/.local/shots/a_{path.split('/')[-1]}.png", full_page=True)
        print("== Aperçu équipe : commande + paiement simulé")
        await pg.goto(BASE+"/commander/emporter"); await pg.wait_for_load_state("networkidle")
        L.check(await pg.get_by_text("Aperçu équipe").count()>0, "bandeau « Aperçu équipe »")
